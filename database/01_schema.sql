SET TIME ZONE 'Asia/Ho_Chi_Minh';

-- -----------------------------------------------------------------------------
-- NHÓM 1: AUTH (Tài khoản và vai trò)
-- -----------------------------------------------------------------------------

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    password_hash TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT chk_users_status CHECK (status IN ('active', 'locked'))
);

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL,
    name VARCHAR(100) NOT NULL,
    CONSTRAINT uq_roles_code UNIQUE (code)
);

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id) REFERENCES roles(id)
);

-- -----------------------------------------------------------------------------
-- NHÓM 2: PATIENT (Hồ sơ bệnh nhân)
-- -----------------------------------------------------------------------------

CREATE TABLE patients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    date_of_birth DATE NULL,
    phone VARCHAR(20) NOT NULL,
    CONSTRAINT uq_patients_user_id UNIQUE (user_id),
    CONSTRAINT fk_patients_user FOREIGN KEY (user_id) REFERENCES users(id)
);

-- -----------------------------------------------------------------------------
-- NHÓM 3: CLINIC (Dịch vụ và tài nguyên phòng khám)
-- -----------------------------------------------------------------------------

CREATE TABLE services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL,
    name VARCHAR(150) NOT NULL,
    kind VARCHAR(20) NOT NULL,
    price NUMERIC(12,0) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_services_code UNIQUE (code),
    CONSTRAINT chk_services_kind CHECK (kind IN ('examination', 'test')),
    CONSTRAINT chk_services_price CHECK (price >= 0)
);

CREATE TABLE resources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    resource_type VARCHAR(30) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_resources_type CHECK (resource_type IN ('consultation_room', 'sampling_station'))
);

-- -----------------------------------------------------------------------------
-- NHÓM 4: BOOKING (Khung giờ, lịch hẹn và lịch sử)
-- -----------------------------------------------------------------------------

CREATE TABLE slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT NOT NULL,
    resource_id BIGINT NOT NULL,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    is_open BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_slots_service FOREIGN KEY (service_id) REFERENCES services(id),
    CONSTRAINT fk_slots_resource FOREIGN KEY (resource_id) REFERENCES resources(id),
    CONSTRAINT uq_slots_resource_starts UNIQUE (resource_id, starts_at),
    CONSTRAINT chk_slots_duration_30m CHECK (ends_at = starts_at + INTERVAL '30 minutes'),
    CONSTRAINT chk_slots_minute_00_30 CHECK (
        EXTRACT(MINUTE FROM (starts_at AT TIME ZONE 'Asia/Ho_Chi_Minh')) IN (0, 30)
        AND EXTRACT(SECOND FROM starts_at) = 0
    )
);

CREATE TABLE appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL,
    slot_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    request_id UUID NOT NULL,
    price_snapshot NUMERIC(12,0) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_appointments_patient FOREIGN KEY (patient_id) REFERENCES patients(id),
    CONSTRAINT fk_appointments_slot FOREIGN KEY (slot_id) REFERENCES slots(id),
    CONSTRAINT uq_appointments_patient_request UNIQUE (patient_id, request_id),
    CONSTRAINT chk_appointments_status CHECK (status IN ('pending', 'confirmed', 'completed', 'cancelled')),
    CONSTRAINT chk_appointments_price_snapshot CHECK (price_snapshot >= 0)
);

CREATE TABLE appointment_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL,
    actor_user_id BIGINT NOT NULL,
    old_status VARCHAR(20) NULL,
    new_status VARCHAR(20) NOT NULL,
    note TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_appointment_history_appointment FOREIGN KEY (appointment_id) REFERENCES appointments(id),
    CONSTRAINT fk_appointment_history_actor FOREIGN KEY (actor_user_id) REFERENCES users(id),
    CONSTRAINT chk_history_old_status CHECK (
        old_status IS NULL OR old_status IN ('pending', 'confirmed', 'completed', 'cancelled')
    ),
    CONSTRAINT chk_history_new_status CHECK (
        new_status IN ('pending', 'confirmed', 'completed', 'cancelled')
    )
);

-- -----------------------------------------------------------------------------
-- CÁC CHỈ MỤC (INDEXES) THEO MỤC 5.2 & 5.4 CỦA BÁO CÁO CHUYÊN ĐỀ 2
-- -----------------------------------------------------------------------------

-- 1. Partial Unique Index ngăn hai lịch chưa hủy chiếm cùng một slot
CREATE UNIQUE INDEX uq_slot_not_cancelled
ON appointments(slot_id)
WHERE status IN ('pending', 'confirmed', 'completed');

-- 2. Chỉ mục phục vụ tra cứu lịch của bệnh nhân và tra cứu khung giờ theo dịch vụ
CREATE INDEX idx_appointments_patient_created
ON appointments(patient_id, created_at);

CREATE INDEX idx_slots_service_starts
ON slots(service_id, starts_at);